-- контекст занятий (вид занятия) — строка на каждую ссылку-событие
INSERT INTO dv.sat_zanyatie (hash_link, tip_zanyatiya)
SELECT l.hash_link,
       CASE
           WHEN l.hash_disciplina = md5('Б1.Б.01') AND l.para = 1 THEN 'лекция'
           WHEN l.hash_disciplina = md5('Б1.Б.01')              THEN 'практика'
           WHEN l.hash_disciplina = md5('Б1.Б.02') AND l.den_nedeli IN (1,2) THEN 'лекция'
           WHEN l.hash_disciplina = md5('Б1.Б.02') AND l.para = 3 AND l.nedelya = 'все'
                AND l.den_nedeli = 3 AND l.hash_gruppa = md5('223-321') THEN 'лабораторная'
           WHEN l.hash_disciplina = md5('Б1.Б.02')              THEN 'лекция'
           WHEN l.hash_disciplina = md5('Б1.Б.03') AND l.para = 2 THEN 'лекция'
           WHEN l.hash_disciplina = md5('Б1.Б.03') AND l.hash_gruppa = md5('223-322') THEN 'лабораторная'
           WHEN l.hash_disciplina = md5('Б1.Б.03')              THEN 'лабораторная'
           WHEN l.hash_disciplina = md5('Б1.Б.04')              THEN 'практика'
           WHEN l.hash_disciplina = md5('Б1.Б.05')              THEN 'лекция'
           WHEN l.hash_disciplina = md5('Б1.В.12') AND l.para = 4 THEN 'лекция'
           ELSE 'лабораторная'
       END
FROM dv.link_zanyatie l;

